// Lexical JSON for the bodies.

const id = () => randomBytes(12).toString('hex')

const text = (value: string, bold = false) => ({
  type: 'text',
  text: value,
  format: bold ? 1 : 0,
  style: '',
  mode: 'normal',
  detail: 0,
  version: 1,
})

/** Text with **bold** runs and [text](url) links (external ones open in a new tab). */
function inline(value: string) {
  return value
    .split(/(\*\*[^*]+\*\*|\[[^\]]+\]\([^)]+\))/)
    .filter(Boolean)
    .map((part) => {
      const bold = part.match(/^\*\*(.+)\*\*$/)
      if (bold) return text(bold[1], true)
      const link = part.match(/^\[(.+)\]\((.+)\)$/)
      if (link) {
        return {
          type: 'link',
          fields: { linkType: 'custom', url: link[2], newTab: link[2].startsWith('http') },
          format: '',
          indent: 0,
          version: 3,
          direction: 'ltr',
          children: [text(link[1])],
        }
      }
      return text(part)
    })
}

const element = { format: '', indent: 0, version: 1, direction: 'ltr' } as const

function node(block: BodyBlock) {
  if (typeof block === 'string') {
    return { type: 'paragraph', ...element, textFormat: 0, children: inline(block) }
  }
  if ('ol' in block) {
    return {
      type: 'list',
      ...element,
      listType: 'number',
      tag: 'ol',
      start: 1,
      children: block.ol.map((item, i) => ({
        type: 'listitem',
        ...element,
        value: i + 1,
        children: inline(item),
      })),
    }
  }
  const fields =
    'table' in block
      ? {
          blockType: 'legalTable',
          columns: block.table.columns.map((label) => ({ id: id(), label })),
          rows: block.table.rows.map((cells) => ({
            id: id(),
            cells: cells.map((value) => ({ id: id(), text: value })),
          })),
        }
      : { blockType: 'legalLink', ...block.link }
  return { type: 'block', format: '', version: 2, fields: { id: id(), blockName: '', ...fields } }
}

/** A section body as Lexical rich text. */
export function legalBody(blocks: BodyBlock[]) {
  return { root: { type: 'root', ...element, children: blocks.map(node) } }
}
